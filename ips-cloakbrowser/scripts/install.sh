#!/usr/bin/env bash
# Install or repair CloakBrowser as the web browser of Claude Code and Codex (macOS).
# Idempotent: rerun it after any breakage or after this skill changes.
set -euo pipefail

SKILL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BIN="$HOME/.local/bin"
SHARE="$HOME/.local/share/ips-cloakbrowser"
LABEL="com.intentplex.ips-cloakbrowser.update"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
LOG="$HOME/Library/Logs/ips-cloakbrowser-update.log"
MARK="<!-- ips-cloakbrowser -->"

say() { printf '\n== %s\n' "$*"; }
need() { command -v "$1" >/dev/null || { echo "missing $1: $2" >&2; exit 1; }; }

[ "$(uname -s)" = Darwin ] || { echo "this installer targets macOS (launchd)" >&2; exit 1; }
export PATH="$BIN:$PATH"
need uv "install from https://docs.astral.sh/uv/"
need npm "install Node.js 18 or newer"
need python3 "install Python 3"
mkdir -p "$BIN" "$SHARE" "$(dirname "$PLIST")" "$(dirname "$LOG")"

if [ "${1:-}" = "--scripts-only" ]; then
  [ -x "$BIN/cloak-fetch" ] || { echo "cloak-fetch is not installed; run the full installer" >&2; exit 1; }
  cp "$SKILL_DIR/scripts/cloak_mcp.py" "$SKILL_DIR/scripts/cloak_fetch.py" "$SHARE/"
  cp "$SKILL_DIR/scripts/cloak-update.sh" "$SHARE/cloak-update.sh"
  chmod +x "$SHARE/cloak-update.sh"
  echo "Synced authoritative skill scripts; no dependencies, binary, registration or launchd changes."
  exit 0
fi
[ "$#" = 0 ] || { echo "usage: install.sh [--scripts-only]" >&2; exit 1; }

say "wrapper (uv tool cloakbrowser)"
uv tool install --upgrade cloakbrowser
TOOL_PY="$(uv tool dir)/cloakbrowser/bin/python"
CLOAK="$(uv tool dir --bin)/cloakbrowser"
[ -x "$TOOL_PY" ] || { echo "uv tool python not found at $TOOL_PY" >&2; exit 1; }

say "binary (~/.cloakbrowser)"
"$CLOAK" install

say "MCP server (@playwright/mcp)"
npm install -g @playwright/mcp@latest --no-fund --no-audit --loglevel=error
NPM_BIN="$(npm prefix -g)/bin"
NODE_DIR="$(dirname "$(command -v node)")"
[ -x "$NPM_BIN/playwright-mcp" ] || { echo "playwright-mcp not found in $NPM_BIN" >&2; exit 1; }

say "commands (cloak-mcp, cloak-fetch, cloak-update in $BIN)"
cp "$SKILL_DIR/scripts/cloak_mcp.py" "$SKILL_DIR/scripts/cloak_fetch.py" "$SHARE/"
cp "$SKILL_DIR/scripts/cloak-update.sh" "$SHARE/cloak-update.sh"
chmod +x "$SHARE/cloak-update.sh"
# Agents and launchd start these with a bare PATH, so each shim pins the tools it needs.
SHIM_PATH="$NPM_BIN:$NODE_DIR:$(dirname "$CLOAK"):$BIN"
for name in mcp fetch; do
  cat >"$BIN/cloak-$name" <<EOF
#!/bin/sh
# generated by ips-cloakbrowser install.sh
export PATH="$SHIM_PATH:\$PATH"
exec "$TOOL_PY" -I "$SHARE/cloak_$name.py" "\$@"
EOF
  chmod +x "$BIN/cloak-$name"
done
cat >"$BIN/cloak-update" <<EOF
#!/bin/sh
# generated by ips-cloakbrowser install.sh
export PATH="$SHIM_PATH:\$PATH"
exec /bin/bash "$SHARE/cloak-update.sh" "\$@"
EOF
chmod +x "$BIN/cloak-update"

say "daily update (launchd $LABEL)"
cat >"$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key><array><string>$BIN/cloak-update</string></array>
  <key>StartCalendarInterval</key><dict><key>Hour</key><integer>9</integer><key>Minute</key><integer>30</integer></dict>
  <key>RunAtLoad</key><true/>
  <key>StandardOutPath</key><string>$LOG</string>
  <key>StandardErrorPath</key><string>$LOG</string>
</dict>
</plist>
EOF
launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"

say "register MCP server 'cloakbrowser'"
# Claude Code: user-scope server in ~/.claude.json (read by the CLI and the desktop app).
python3 - "$BIN/cloak-mcp" <<'PY'
import json, os, sys
path = os.path.expanduser("~/.claude.json")
data = json.load(open(path)) if os.path.exists(path) else {}
entry = {"type": "stdio", "command": sys.argv[1], "args": [], "env": {}}
if data.get("mcpServers", {}).get("cloakbrowser") != entry:
    data.setdefault("mcpServers", {})["cloakbrowser"] = entry
    tmp = f"{path}.{os.getpid()}.tmp"
    with open(tmp, "w") as f:
        json.dump(data, f, indent=2)
    os.replace(tmp, path)
    print("claude: registered")
else:
    print("claude: already registered")
PY
if command -v codex >/dev/null; then
  # `codex mcp add` rewrites every [mcp_servers] table, so only call it when needed.
  if codex mcp get cloakbrowser 2>/dev/null | grep -qx "  command: $BIN/cloak-mcp"; then
    echo "codex: already registered"
  else
    codex mcp remove cloakbrowser >/dev/null 2>&1 || true
    codex mcp add cloakbrowser -- "$BIN/cloak-mcp"
  fi
else
  echo "codex: not installed, skipped"
fi

say "agent instructions (~/.claude/CLAUDE.md, ~/.codex/AGENTS.md)"
for target in "$HOME/.claude/CLAUDE.md" "$HOME/.codex/AGENTS.md"; do
  [ -d "$(dirname "$target")" ] || continue
  python3 - "$target" "$SKILL_DIR/references/agent-instructions.md" "$MARK" <<'PY'
import sys
target, source, mark = sys.argv[1:]
block = f"{mark}\n{open(source).read().strip()}\n{mark}\n"
try:
    text = open(target).read()
except FileNotFoundError:
    text = ""
parts = text.split(mark)
if len(parts) >= 3:  # replace the existing block in place
    text = parts[0] + block + mark.join(parts[2:]).lstrip("\n")
else:
    text = (text.rstrip("\n") + "\n\n" if text.strip() else "") + block
open(target, "w").write(text)
print(f"{target}: updated")
PY
done

say "verify"
"$BIN/cloak-fetch" https://example.com | head -n 4
echo
echo "Done. Start a new Claude Code / Codex session to load the cloakbrowser MCP tools."
